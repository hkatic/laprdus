//! Built-in accent lexicon of Croatian.
//!
//! Stress in Croatian is lexical. The front end defaults to the first
//! syllable (the most common Neo-Štokavian position) and applies suffix
//! rules; this lexicon covers frequent words those do not get right, plus
//! vowel length and tone for very common words.
//!
//! The notation is that of [`crate::text::frontend::notation`]. An exact
//! form always wins over a stem, and the longest stem over shorter ones.
//! Where a spelling belongs to two words (obavijesti: the noun's cases and
//! the verb's imperative), the noun gets it.
//!
//! Place names and personal names are tables of their own, generated by
//! `tools/formant/proper_names.py` from `tools/formant/places.tsv` and
//! `tools/formant/persons.tsv` (the accented forms and their sources): towns,
//! villages and regions and given names and surnames of Croatia, Bosnia and
//! Herzegovina, Serbia, Montenegro, North Macedonia and Slovenia whose case
//! forms the rules get wrong, with the accents of the dictionaries. They are
//! used only for words written with a capital letter; "=" before an entry
//! marks a name spelled like a common word, not used for the first word of a
//! clause. One entry per line, in the notation.

mod entries;
mod verbs;

pub(crate) use verbs::{IJE_VERBS, VERBS};

use crate::text::frontend::letters::chars;
use crate::text::frontend::notation::{LexEntry, for_each_form, parse_lex_entry};
use std::collections::{HashMap, HashSet};
use std::sync::LazyLock;

/// Accent entries by their plain spelling.
pub type Entries = HashMap<Vec<char>, LexEntry>;

/// The lexicon, as the front end looks words up.
#[derive(Debug, Default)]
pub struct Lexicon {
    pub exact: Entries,
    pub stems: Entries,
    /// Places and persons: capitalized words only.
    pub proper: Entries,
    /// ... and not first in a clause.
    pub proper_mid: HashSet<Vec<char>>,
}

impl Lexicon {
    fn build() -> Self {
        let mut lexicon = Lexicon::default();
        // A later entry of the table overrides an earlier one of the same
        // spelling.
        for entry in entries::ENTRIES {
            for_each_form(&chars(entry), |form| {
                if let Ok(parsed) = parse_lex_entry(form) {
                    let entries = if parsed.stem { &mut lexicon.stems } else { &mut lexicon.exact };
                    entries.insert(parsed.plain, parsed.entry);
                }
            });
        }
        // Place names, then personal names, which win over a place of the
        // same spelling; within a table a later line wins.
        for table in [include_str!("../tables/places.txt"), include_str!("../tables/persons.txt")] {
            for entry in table.lines() {
                for_each_form(&chars(entry), |form| {
                    // "=" before an entry: a name spelled like a common word, not
                    // used for the first word of a clause
                    let (mid, form) = match form {
                        ['=', rest @ ..] => (true, rest),
                        _ => (false, form),
                    };
                    if let Ok(parsed) = parse_lex_entry(form)
                        && !parsed.stem
                    {
                        if mid {
                            lexicon.proper_mid.insert(parsed.plain.clone()); // never cleared by a later entry
                        }
                        lexicon.proper.insert(parsed.plain, parsed.entry);
                    }
                });
            }
        }
        lexicon
    }

    /// The built-in lexicon, built when the language is first spoken: the
    /// first time a front end reads it, not when the front end is made (an
    /// engine starts with a Croatian front end whatever it goes on to speak,
    /// and built these tables for a host that never spoke Croatian).
    pub fn builtin() -> &'static LazyLock<Lexicon> {
        static LEXICON: LazyLock<Lexicon> = LazyLock::new(Lexicon::build);
        &LEXICON
    }
}
