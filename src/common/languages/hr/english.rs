use crate::text::frontend::letters::{ends_with, ends_with_any, find, find_from, is_consonant_letter, is_vowel_letter};
use std::cmp::Ordering;
use std::sync::LazyLock;

static TABLE: &str = include_str!("tables/english.txt");

/// The lines of the table.
static LINES: LazyLock<Vec<&'static str>> = LazyLock::new(|| TABLE.lines().collect());

/// Only the letters a to z: no č, ć, đ, š, ž.
fn english_spelling_letters(s: &[char]) -> bool {
    s.iter().all(char::is_ascii_lowercase)
}

/// Spellings no Croatian word has: the letters q, w, x
/// and y; th, ch, gh, ph and ck (not before a vowel); sh at the end, -tion
/// and -sion; i before a, e or u (the languages write ija, ije, iju); a
/// doubled consonant. (Not cl: clanak, clanarina are članak, članarina typed
/// without the háček.) A native word has some of them where
/// a prefix meets its root, and those places do not count: prethodni,
/// pothvat, othraniti, neophodan, najneophodniji, preothraniti (pret-,
/// pot-, ot-, op- before h, after ne-, naj- or pre-), iako,
/// priupitati, antialergijski, poliester, arhiepiskop (i-, pri-, anti-,
/// poli-, arhi- before a vowel), izvannastavni, posttraumatski,
/// transseksualan (a prefix before its own last consonant); the longer
/// prefixes also inside a compound (aerotriangulacija). dd, jj and zz are
/// native (oddaljiti, najjači, bezzvučan).
pub fn english_spelling(s: &[char]) -> bool {
    if !english_spelling_letters(s) {
        return false;
    }
    // Is s[..end] one of the prefixes, alone or after ne- or naj-?
    let prefix = |end: usize, prefixes: &[&str]| {
        let head = &s[..end];
        prefixes.iter().any(|p| {
            ["", "ne", "naj", "najne", "pre", "nepre"].iter().any(|neg| {
                head.len() == neg.len() + p.len() && ends_with(head, p) && ends_with(&head[..neg.len()], neg)
            })
        })
    };
    // ... or does it end with one of them?
    let prefix_end = |end: usize, prefixes: &[&str]| ends_with_any(&s[..end], prefixes);
    // Every place a pair of letters stands
    let places = |pair: &'static str| std::iter::successors(find(s, pair), move |&at| find_from(s, pair, at + 1));

    if s.iter().any(|c| matches!(c, 'q' | 'w' | 'x' | 'y')) || find(s, "ch").is_some() || find(s, "gh").is_some() {
        return true;
    }
    if places("th").any(|i| !prefix(i + 1, &["pret", "pot", "ot", "nat", "post"]))
        || places("ph").any(|i| !prefix(i + 1, &["op"]))
        || places("ck").any(|i| !s.get(i + 2).is_some_and(|&c| is_vowel_letter(c)))
        || ends_with_any(s, &["sh", "tion", "tions", "sion", "sions"])
    {
        return true;
    }
    s.windows(2).enumerate().any(|(i, pair)| {
        let next = pair[1];
        (pair[0] == 'i'
            && matches!(next, 'a' | 'e' | 'u')
            && !prefix(i + 1, &["i", "bi"])
            && !prefix_end(i + 1, &["pri", "tri", "anti", "poli", "multi", "semi", "arhi"]))
            || (pair[0] == next
                && is_consonant_letter(next)
                && !matches!(next, 'd' | 'j' | 'z')
                && !prefix_end(i + 1, &["van", "hiper", "super", "post", "trans", "inter"]))
    })
}

/// Compares a word with the letters of an entry of the English table (its
/// stress mark skipped): `Less` when the word comes first.
fn compare_english(key: &[char], entry: &str) -> Ordering {
    let mut letters = key.iter();
    for c in entry.chars().filter(|&c| c != '\'') {
        match letters.next() {
            None => return Ordering::Less,
            Some(&k) if k != c => return k.cmp(&c),
            Some(_) => {}
        }
    }
    if letters.next().is_none() { Ordering::Equal } else { Ordering::Greater }
}

/// An entry of the English table: the letter its stress mark precedes, or
/// `None` for an entry without a mark: a native word that is an English word
/// of the table with a case ending (reforma, republici, nadala: reform,
/// republic, Nadal), or a native name spelled without its j (Emilia, Julia:
/// Emilija, Julija). The outer `None`: not in the table.
pub fn english_entry(key: &[char]) -> Option<Option<usize>> {
    // The last line whose first entry is not after the word
    let after = LINES
        .partition_point(|line| compare_english(key, line.split(' ').next().unwrap_or_default()) != Ordering::Less);
    for entry in LINES.get(after.checked_sub(1)?)?.split(' ') {
        match compare_english(key, entry) {
            Ordering::Equal => return Some(entry.find('\'')),
            Ordering::Less => return None,
            Ordering::Greater => {}
        }
    }
    None
}

/// A word of the English table, also with the endings that leave the English
/// stress where it is (darkness, basically, companies; for a word spelled
/// the English way also settings, created, stopping, players), and with a
/// Croatian case ending (managera, Jacksona, Chicagu, iPhonea). Native words
/// end in -s, -ed, -er, -ing and -ment too, and with those taken off some
/// are English words (operater, distributer: operate, distribute), so a word
/// spelled the native way loses only an ending no native word has, and a
/// case ending only down to a word of the table itself; the native words
/// that would then be taken for one (reforma, republici) are in the table
/// as such. tools/formant/english_words.py leaves out of the table every
/// word this finds through another one, so the two must agree: change both
/// together. Returns the letter the stress mark precedes.
pub fn english_word(s: &[char], english_shape: bool) -> Option<usize> {
    english_word_at(s, english_shape, 0)
}

/// [`english_word`] at a depth of endings taken off.
fn english_word_at(s: &[char], english_shape: bool, depth: u8) -> Option<usize> {
    if let Some(stress) = english_entry(s) {
        return stress;
    }
    if depth >= 2 {
        return None;
    }
    // The ending, what stands in its place in the base word, and whether
    // native words end so too
    const ENDINGS: [(&str, &str, bool); 24] = [
        ("ies", "y", false),
        ("ied", "y", false),
        ("ily", "y", false),
        ("iness", "y", false),
        ("ier", "y", false),
        ("ments", "", false),
        ("ment", "", true),
        ("ness", "", false),
        ("less", "", false),
        ("ful", "", false),
        ("ally", "", false),
        ("ly", "", false),
        ("ing", "", true),
        ("ing", "e", true),
        ("ed", "", true),
        ("ed", "e", true),
        ("ers", "", true),
        ("ers", "e", true),
        ("er", "", true),
        ("er", "e", true),
        ("est", "", true),
        ("est", "e", true),
        ("es", "", true),
        ("s", "", true),
    ];
    let with = |base: &[char], restore: &str| -> Vec<char> { base.iter().copied().chain(restore.chars()).collect() };
    for (ending, restore, native) in ENDINGS {
        if (native && !english_shape) || s.len() < ending.len() + 3 || !ends_with(s, ending) {
            continue;
        }
        let stem = &s[..s.len() - ending.len()];
        if ending == "s" && (ends_with(stem, "s") || ends_with(stem, "u")) {
            continue;
        }
        let found = english_word_at(&with(stem, restore), english_shape, depth + 1).or_else(|| {
            // stopped, getting: the consonant doubled before the ending
            match stem {
                [.., _, a, b] if restore.is_empty() && a == b && is_consonant_letter(*b) => {
                    english_word_at(&stem[..stem.len() - 1], english_shape, depth + 1)
                }
                _ => None,
            }
        });
        if found.is_some() {
            return found;
        }
    }
    if depth == 0 {
        const CASES: [&str; 16] = [
            "ovima", "ovom", "ovoj", "ovih", "ovim", "ova", "ove", "ovi", "ovu", "ima", "om", "em", "a", "u", "e", "i",
        ];
        for ending in CASES {
            if s.len() < ending.len() + 3 || !ends_with(s, ending) {
                continue;
            }
            let base = &s[..s.len() - ending.len()];
            // Chicago, Chicagu; Seattle, Seattlea
            for restore in ["", "o", "e", "a"] {
                let word = with(base, restore);
                let found = if english_shape {
                    english_word_at(&word, true, depth + 1)
                } else {
                    english_entry(&word).flatten()
                };
                if found.is_some_and(|stress| stress < base.len()) {
                    return found;
                }
            }
        }
    }
    None
}

/// Stress of an English word that is not in the table: on the syllable
/// before the endings that put it there (Croàtian, musìcian, Austràlia,
/// elèctronic, univèrsity, delìcious), on the ending for the few that carry
/// it (engineèr, Chinèse, cassètte, ballòon, uníque, biòlogy, photògraphy,
/// thermòmeter, astrònomy), and otherwise on the first syllable, where most
/// English words of two and three syllables and most names have it
/// (Ábleton, Sámsung, Hílton). A plural -s and a Croatian case ending do
/// not count (musicians, Sebastianu). `nucleus_letters` holds the letter of
/// the spelling each nucleus comes from.
pub fn english_rule(s: &[char], nucleus_letters: &[usize]) -> usize {
    const BEFORE: [&str; 23] = [
        "tion", "sion", "cian", "tian", "sian", "cial", "tial", "cious", "tious", "gious", "geous", "ious", "ian",
        "ial", "ium", "ia", "ically", "ical", "ics", "ic", "ity", "ety", "ify",
    ];
    const ON: [&str; 10] = ["ography", "ology", "ometer", "onomy", "eer", "ese", "ette", "esque", "oon", "ique"];
    const CASES: [&str; 12] = ["", "s", "a", "u", "e", "i", "om", "em", "ima", "ama", "ov", "ova"];
    for ending in CASES {
        if !ends_with(s, ending) || s.len() < ending.len() + 4 {
            continue;
        }
        let w = &s[..s.len() - ending.len()];
        if ending == "s" && ends_with(w, "s") {
            continue;
        }
        let suffix_at =
            |suffix: &&str| (w.len() > suffix.len() && ends_with(w, suffix)).then(|| w.len() - suffix.len());
        if let Some(at) = BEFORE.iter().find_map(suffix_at) {
            return nucleus_letters.iter().rposition(|&letter| letter < at).unwrap_or(0);
        }
        if let Some(at) = ON.iter().find_map(suffix_at) {
            return nucleus_letters.iter().skip(1).position(|&letter| letter >= at).map_or(0, |k| k + 1);
        }
    }
    0
}
