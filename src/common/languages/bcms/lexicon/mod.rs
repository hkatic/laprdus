//! Built-in accent lexicon of Croatian, Serbian and Bosnian.
//!
//! Stress in Croatian/Serbian/Bosnian is lexical. The front end defaults to
//! the first syllable (the most common Neo-Štokavian position) and applies
//! suffix rules; this lexicon covers frequent words those do not get right,
//! plus vowel length and tone for very common words.
//!
//! The notation is that of [`crate::text::frontend::notation`]. An exact
//! form always wins over a stem, and the longest stem over shorter ones.
//! Where a spelling belongs to two words (obavijesti: the noun's cases and
//! the verb's imperative), the noun gets it.
//!
//! Place names and personal names are tables of their own, generated by
//! `tools/formant/proper_names.py` from `tools/formant/places.tsv` and
//! `tools/formant/persons.tsv` (the accented forms and their sources): towns,
//! villages and regions and given names and surnames of Croatia, Bosnia and
//! Herzegovina, Serbia, Montenegro, North Macedonia and Slovenia whose case
//! forms the rules get wrong, with the accents of the dictionaries. They are
//! used only for words written with a capital letter; "=" before an entry
//! marks a name spelled like a common word, not used for the first word of a
//! clause. One entry per line, in the notation.

mod bs;
mod common;
mod hr;
mod sr;
mod verbs;

pub(crate) use verbs::{IJE_VERBS, VERBS};

use crate::language::Language;
use crate::text::frontend::letters::chars;
use crate::text::frontend::notation::{LexEntry, for_each_form, parse_lex_entry};
use std::collections::{HashMap, HashSet};
use std::sync::LazyLock;

/// Accent entries by their plain spelling.
pub type Entries = HashMap<Vec<char>, LexEntry>;

/// The lexicon of one language, as the front end looks words up.
#[derive(Debug, Default)]
pub struct Lexicon {
    pub exact: Entries,
    pub stems: Entries,
    /// Places and persons: capitalized words only.
    pub proper: Entries,
    /// ... and not first in a clause.
    pub proper_mid: HashSet<Vec<char>>,
}

impl Lexicon {
    fn build(language: Language) -> Self {
        let places_common = include_str!("../tables/places_common.txt");
        let persons_common = include_str!("../tables/persons_common.txt");
        let (own, places, persons) = match language {
            Language::Serbian => {
                (sr::SERBIAN, include_str!("../tables/places_sr.txt"), include_str!("../tables/persons_sr.txt"))
            }
            Language::Bosnian => {
                (bs::BOSNIAN, include_str!("../tables/places_bs.txt"), include_str!("../tables/persons_bs.txt"))
            }
            _ => (hr::CROATIAN, include_str!("../tables/places_hr.txt"), include_str!("../tables/persons_hr.txt")),
        };

        let mut lexicon = Lexicon::default();
        // Later (language-specific) tables override the common one.
        for entry in common::COMMON.iter().chain(own) {
            for_each_form(&chars(entry), |form| {
                if let Ok(parsed) = parse_lex_entry(form) {
                    let entries = if parsed.stem { &mut lexicon.stems } else { &mut lexicon.exact };
                    entries.insert(parsed.plain, parsed.entry);
                }
            });
        }
        // Place names, then personal names (which win over a place of the same
        // spelling): the common table, then the language's own forms
        for table in [places_common, places, persons_common, persons] {
            for entry in table.lines() {
                for_each_form(&chars(entry), |form| {
                    // "=" before an entry: a name spelled like a common word, not
                    // used for the first word of a clause
                    let (mid, form) = match form {
                        ['=', rest @ ..] => (true, rest),
                        _ => (false, form),
                    };
                    if let Ok(parsed) = parse_lex_entry(form)
                        && !parsed.stem
                    {
                        if mid {
                            lexicon.proper_mid.insert(parsed.plain.clone()); // never cleared by a later entry
                        }
                        lexicon.proper.insert(parsed.plain, parsed.entry);
                    }
                });
            }
        }
        lexicon
    }

    /// The lexicon of Croatian, Serbian or Bosnian, built when the language
    /// is first spoken. Slovenian has a lexicon of its own: for it this one
    /// is empty.
    pub fn of(language: Language) -> &'static Lexicon {
        static LEXICONS: [LazyLock<Lexicon>; 4] = [
            LazyLock::new(|| Lexicon::build(Language::Croatian)),
            LazyLock::new(|| Lexicon::build(Language::Serbian)),
            LazyLock::new(|| Lexicon::build(Language::Bosnian)),
            LazyLock::new(Lexicon::default),
        ];
        &LEXICONS[language as usize]
    }
}
